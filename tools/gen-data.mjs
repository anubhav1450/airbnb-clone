// NOTE: photos.js is hand-corrected for the Bedroom subtitle (the dump used to truncate text at 140 chars; now 600).
// Generates src/data/photos.js and src/data/amenityData.js from captures of the reference
// (tools/captures/*.json). Re-run only if the captures change.
import fs from 'node:fs'
const cap = (n) => JSON.parse(fs.readFileSync(new URL('./captures/' + n, import.meta.url)))
const dump = cap('pp-ref-dump.json')
const els = dump.els
const kids = new Map()
for (const e of els) (kids.get(e.p) || kids.set(e.p, []).get(e.p)).push(e)
const desc = (e, f, out = []) => { for (const c of kids.get(e.id) || []) { if (f(c)) out.push(c); desc(c, f, out) } return out }

const rooms = els.filter((e) => e.a && /^tour-room-\d+$/.test(e.a.id)).map((sec) => {
  const texts = desc(sec, (c) => c.txt)
  const btns = desc(sec, (c) => c.t === 'button' && c.a && /image \d+$/.test(c.a['aria-label'] || ''))
  const imgs = desc(sec, (c) => c.t === 'img' && c.a && c.a.src).map((i) => i.a.src)
  const layout = btns.map((b) => (b.w > 300 ? 'L' : 's')).join('')
  return { id: sec.a.id, title: texts[0]?.txt || '', subtitle: texts[1]?.txt || '', photos: imgs, layout }
})
const nav = els.find((e) => e.a && e.a.id === 'tourNav')
const thumbs = desc(nav, (c) => c.t === 'img').map((i) => i.a.src)
rooms.forEach((r, i) => { r.thumb = thumbs[i] })

const hero = desc(els.find((e) => e.a && e.a.id === 'heroGrid'), (c) => c.t === 'img').map((i) => i.a.src)
const js = `// Generated by tools/gen-data.mjs from the reference's rendered gallery. Files live in public/assets/photos.
export const PHOTO_DIR = '/assets/photos/'
export const HERO = ${JSON.stringify(hero)}
export const ROOMS = ${JSON.stringify(rooms.map(({ title, subtitle, thumb, photos, layout }) => ({ title, subtitle, thumb, layout, photos })), null, 1)}
`
fs.writeFileSync(new URL('../src/data/photos.js', import.meta.url), js)
console.log('rooms', rooms.map((r) => r.title + ':' + r.photos.length).join(', '), 'hero', hero.length, 'thumbs', thumbs.length)

const amen = cap('pp-ref-amen.json')
const cats = []
const icons = {}
for (const r of amen) {
  let c = cats.find((x) => x.title === r.cat)
  if (!c) cats.push((c = { title: r.cat, items: [] }))
  c.items.push({ label: r.label, ...(r.strike ? { unavailable: true } : {}) })
  icons[r.label] = r.svg.replace(/\s+/g, ' ')
}
fs.writeFileSync(new URL('../src/data/amenityData.js', import.meta.url),
  `// Generated by tools/gen-data.mjs — amenity groups (dialog) and one icon per amenity label.\nexport const AMENITY_GROUPS = ${JSON.stringify(cats, null, 1)}\nexport const AMENITY_ICONS = ${JSON.stringify(icons, null, 1)}\n`)
console.log('amen groups', cats.length, 'icons', Object.keys(icons).length)
